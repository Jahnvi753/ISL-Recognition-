import numpy as np


def get_graph(num_nodes=75):
    """
    Build a graph for:
    33 pose landmarks
    21 left-hand landmarks
    21 right-hand landmarks
    """

    edges = []

    # -------------------------------------------------
    # Pose landmarks: 0-32
    # -------------------------------------------------
    pose_edges = [
        (0, 1), (1, 2), (2, 3), (3, 7),
        (0, 4), (4, 5), (5, 6), (6, 8),
        (9, 10),
        (11, 12),
        (11, 13), (13, 15),
        (12, 14), (14, 16),
        (11, 23), (12, 24),
        (23, 24),
        (23, 25), (25, 27),
        (27, 29), (29, 31),
        (24, 26), (26, 28),
        (28, 30), (30, 32),
    ]

    edges.extend(pose_edges)

    # -------------------------------------------------
    # Left hand: nodes 33-53
    # -------------------------------------------------
    left_hand_edges = [
        (0, 1), (1, 2), (2, 3), (3, 4),
        (0, 5), (5, 6), (6, 7), (7, 8),
        (0, 9), (9, 10), (10, 11), (11, 12),
        (0, 13), (13, 14), (14, 15), (15, 16),
        (0, 17), (17, 18), (18, 19), (19, 20),
        (5, 9), (9, 13), (13, 17),
    ]

    for a, b in left_hand_edges:
        edges.append((a + 33, b + 33))

    # -------------------------------------------------
    # Right hand: nodes 54-74
    # -------------------------------------------------
    right_hand_edges = [
        (0, 1), (1, 2), (2, 3), (3, 4),
        (0, 5), (5, 6), (6, 7), (7, 8),
        (0, 9), (9, 10), (10, 11), (11, 12),
        (0, 13), (13, 14), (14, 15), (15, 16),
        (0, 17), (17, 18), (18, 19), (19, 20),
        (5, 9), (9, 13), (13, 17),
    ]

    for a, b in right_hand_edges:
        edges.append((a + 54, b + 54))

    # -------------------------------------------------
    # Connect pose wrists to hand wrists
    # MediaPipe pose:
    # left wrist = 15
    # right wrist = 16
    # -------------------------------------------------
    edges.append((15, 33))
    edges.append((16, 54))

    # -------------------------------------------------
    # Add self connections
    # -------------------------------------------------
    for i in range(num_nodes):
        edges.append((i, i))

    # -------------------------------------------------
    # Build adjacency matrix
    # -------------------------------------------------
    A = np.zeros((num_nodes, num_nodes), dtype=np.float32)

    for i, j in edges:
        A[i, j] = 1
        A[j, i] = 1

    # -------------------------------------------------
    # Normalize adjacency matrix
    # -------------------------------------------------
    degree = A.sum(axis=1)
    degree_inv_sqrt = np.power(degree, -0.5)
    degree_inv_sqrt[np.isinf(degree_inv_sqrt)] = 0

    D = np.diag(degree_inv_sqrt)

    A = D @ A @ D

    return A